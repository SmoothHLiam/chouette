/* Chouette ! — teacher-authored word and sentence lists.
 *
 * These sit ALONGSIDE the built-in banks, never replacing them. An assignment
 * with no list attached plays exactly as it always has, on the vocabulary and
 * sentences that ship with the game. Attaching a list swaps the content for
 * that session only.
 *
 * A list is stored on its class, so it reaches students through the same sync
 * the class itself uses.
 */
(function (global) {
  "use strict";
  var App = (global.App = global.App || {});
  var U = App.U;

  var LIMITS = { lists: 20, items: 200, name: 60, field: 120 };

  var KINDS = [
    { id: "vocab", name: "Mots", icon: "🔤",
      hint: "Des paires français / anglais, comme « le chien = dog »." },
    { id: "sentences", name: "Phrases", icon: "💬",
      hint: "Des phrases entières, comme « J'ai un chien. = I have a dog. »" }
  ];

  /* Which games a list can actually drive. Anything not named here keeps using
   * the built-in content: Conjugaison Rush is generated by the verb engine, and
   * Révision Ciblée is built from the student's own mistakes. */
  var GAME_NEEDS = {
    eclair: { kinds: ["vocab"], min: 4 },
    memoire: { kinds: ["vocab"], min: 4 },
    accents: { kinds: ["vocab"], min: 4, needs: "accented" },
    genre: { kinds: ["vocab"], min: 4, needs: "nouns" },
    ecoute: { kinds: ["vocab", "sentences"], min: 4 },
    phrase: { kinds: ["sentences"], min: 3 },
    boss: { kinds: ["vocab"], min: 4 }
  };

  var ACCENTED = /[éèêëàâùûîïôçœ]/i;
  /* Tab first — a list pasted straight out of a spreadsheet arrives that way. */
  var SEPARATORS = ["\t", "=", ";", "|", " — ", " – ", " - ", ":"];

  function splitLine(line) {
    for (var i = 0; i < SEPARATORS.length; i++) {
      var at = line.indexOf(SEPARATORS[i]);
      if (at > 0) {
        return [line.slice(0, at), line.slice(at + SEPARATORS[i].length)];
      }
    }
    return null;
  }

  /** "le chien" -> { fr: "chien", g: "m" } · "l'eau (f)" -> { fr: "eau", g: "f" } */
  function readFrench(text) {
    var fr = text.trim();
    var g = null;

    var marked = fr.match(/\s*\((m|f|m\.|f\.|masc|fém|fem)\)\s*$/i);
    if (marked) {
      g = marked[1].toLowerCase().charAt(0) === "m" ? "m" : "f";
      fr = fr.slice(0, marked.index).trim();
    }

    /* Longest first: alternation is ordered, so "le" would otherwise match
     * inside "les gens" and "un" inside "une pomme", inventing a gender and
     * eating a letter of the word. */
    var article = fr.match(/^(l'|les|la|le|une|un)\s*/i);
    if (article) {
      var word = article[1].toLowerCase();
      if (!g) {
        if (word === "le" || word === "un") g = "m";
        else if (word === "la" || word === "une") g = "f";
      }
      // "l'" and "les" hide the gender, so they only get stripped, never guessed.
      if (word === "l'") fr = fr.slice(article[0].length).trim();
      else fr = fr.slice(article[0].length).trim();
    }
    return { fr: fr, g: g };
  }

  /** Turns pasted text into items. Reports what it could not read, by line. */
  function parse(text, kind, englishFirst) {
    var items = [];
    var problems = [];
    String(text || "").split(/\r?\n/).forEach(function (raw, index) {
      var line = raw.trim();
      if (!line || line.charAt(0) === "#") return;
      var parts = splitLine(line);
      if (!parts) {
        problems.push({ line: index + 1, text: line, why: "pas de séparateur (=, tabulation, ;)" });
        return;
      }
      var left = parts[0].trim();
      var right = parts[1].trim();
      var frRaw = englishFirst ? right : left;
      var enRaw = englishFirst ? left : right;
      if (!frRaw || !enRaw) {
        problems.push({ line: index + 1, text: line, why: "un des deux côtés est vide" });
        return;
      }
      if (kind === "sentences") {
        items.push({
          fr: frRaw.slice(0, LIMITS.field),
          en: enRaw.slice(0, LIMITS.field)
        });
      } else {
        var parsed = readFrench(frRaw);
        if (!parsed.fr) {
          problems.push({ line: index + 1, text: line, why: "le côté français est vide" });
          return;
        }
        items.push({
          fr: parsed.fr.slice(0, LIMITS.field),
          en: enRaw.slice(0, LIMITS.field),
          g: parsed.g
        });
      }
    });
    return { items: items.slice(0, LIMITS.items), problems: problems };
  }

  /** Back to editable text, so a list can be reopened and corrected. */
  function toText(list) {
    return (list.items || []).map(function (item) {
      if (list.kind === "sentences") return item.fr + " = " + item.en;
      var fr = item.g === "m" ? "le " + item.fr : item.g === "f" ? "la " + item.fr : item.fr;
      return fr + " = " + item.en;
    }).join("\n");
  }

  function capabilities(list) {
    var items = (list && list.items) || [];
    var nouns = 0, accented = 0;
    if (list && list.kind === "vocab") {
      items.forEach(function (item) {
        if (item.g === "m" || item.g === "f") nouns++;
        if (ACCENTED.test(item.fr)) accented++;
      });
    }
    return { total: items.length, nouns: nouns, accented: accented };
  }

  /** Can this list drive that game? */
  function supports(list, gameId) {
    var need = GAME_NEEDS[gameId];
    if (!list || !need) return false;
    if (need.kinds.indexOf(list.kind) === -1) return false;
    var caps = capabilities(list);
    if (caps.total < need.min) return false;
    if (need.needs === "nouns" && caps.nouns < need.min) return false;
    if (need.needs === "accented" && caps.accented < need.min) return false;
    return true;
  }

  function gamesFor(list) {
    return Object.keys(GAME_NEEDS).filter(function (id) { return supports(list, id); });
  }

  /** Why a game is greyed out, in words a teacher can act on. */
  function whyNot(list, gameId) {
    var need = GAME_NEEDS[gameId];
    if (!need) return "ce jeu utilise le contenu intégré";
    if (need.kinds.indexOf(list.kind) === -1) {
      return need.kinds.indexOf("sentences") !== -1 ? "demande une liste de phrases" : "demande une liste de mots";
    }
    var caps = capabilities(list);
    if (need.needs === "nouns" && caps.nouns < need.min) return "demande au moins " + need.min + " noms avec le/la";
    if (need.needs === "accented" && caps.accented < need.min) return "demande au moins " + need.min + " mots accentués";
    if (caps.total < need.min) return "demande au moins " + need.min + " entrées";
    return "";
  }

  /* --------------------------------------------------- game-ready decks -- */

  /** Custom items wear the same shape as the built-in bank, so every game and
   *  helper (articles, gender filters, mastery keys) works unchanged. */
  function asVocab(list) {
    return (list.items || []).map(function (item) {
      return {
        fr: item.fr,
        en: item.en,
        g: item.g || null,
        t: item.g ? "n" : "e",
        c: list.name,
        custom: true
      };
    });
  }

  function asSentences(list) {
    return (list.items || []).map(function (item) {
      return { fr: item.fr, en: item.en, custom: true };
    });
  }

  /* -------------------------------------------------------- persistence -- */

  function newId() {
    return "l" + Date.now().toString(36) + Math.random().toString(36).slice(2, 5);
  }

  function all(code) {
    var klass = App.School.get(code);
    return (klass && klass.lists) || [];
  }

  function get(code, id) {
    return all(code).filter(function (l) { return l.id === id; })[0] || null;
  }

  function save(code, draft) {
    var klass = App.School.get(code);
    if (!klass) return null;
    if (!klass.lists) klass.lists = [];
    var record = {
      id: draft.id || newId(),
      name: String(draft.name || "Ma liste").trim().slice(0, LIMITS.name) || "Ma liste",
      kind: draft.kind === "sentences" ? "sentences" : "vocab",
      items: (draft.items || []).slice(0, LIMITS.items),
      created: draft.created || Date.now(),
      edited: Date.now()
    };
    var index = -1;
    klass.lists.forEach(function (l, i) { if (l.id === record.id) index = i; });
    if (index >= 0) klass.lists[index] = record;
    else {
      if (klass.lists.length >= LIMITS.lists) return null;
      klass.lists.push(record);
    }
    App.School.put(klass);
    return record;
  }

  function remove(code, id) {
    var klass = App.School.get(code);
    if (!klass || !klass.lists) return false;
    var before = klass.lists.length;
    klass.lists = klass.lists.filter(function (l) { return l.id !== id; });
    // An assignment pointing at a deleted list falls back to the built-in bank
    // rather than becoming impossible to finish.
    (klass.assignments || []).forEach(function (a) {
      if (a.listId === id) delete a.listId;
    });
    if (klass.lists.length !== before) { App.School.put(klass); return true; }
    return false;
  }

  App.Lists = {
    LIMITS: LIMITS,
    KINDS: KINDS,
    GAME_NEEDS: GAME_NEEDS,
    parse: parse,
    toText: toText,
    capabilities: capabilities,
    supports: supports,
    gamesFor: gamesFor,
    whyNot: whyNot,
    asVocab: asVocab,
    asSentences: asSentences,
    all: all,
    get: get,
    save: save,
    remove: remove
  };

  if (typeof module !== "undefined" && module.exports) module.exports = App.Lists;
})(typeof window !== "undefined" ? window : globalThis);
